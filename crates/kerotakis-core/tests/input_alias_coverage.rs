//! Generated input aliases: coverage table, collision refusals and identity
//! boundaries. Aliases are spellings of existing registry identities only.
use std::collections::BTreeMap;

use kerotakis_core::script::parse_op;
use kerotakis_core::species::{self, InputAliasTable, INPUT_ALIAS_SOURCES};
use kerotakis_core::*;

const FIXTURE: &str = "tests/fixtures/input-alias-coverage-20261027.json";
const DOC: &str = "../../docs/input-alias-coverage-20261027.md";
const BLESS: &str = "KEROTAKIS_BLESS_ALIAS_COVERAGE";

/// The seven reviewed mappings from #787/#789/#807 must survive generation.
const CURATED: &[(&str, &str)] = &[
    ("H2O", "water"),
    ("oxygen", "O2"),
    ("nitrogen", "N2"),
    ("carbon dioxide", "CO2"),
    ("sodium chloride", "NaCl"),
    ("CuSO4_anhydrous", "CuSO4"),
    ("acetate", "CH3COO-"),
];

fn render_markdown(table: &InputAliasTable) -> String {
    let registry = species::registry();
    let mut counts: BTreeMap<&str, usize> = BTreeMap::new();
    for alias in &table.aliases {
        *counts.entry(alias.source.as_str()).or_default() += 1;
    }
    let missing: Vec<&str> = registry
        .iter()
        .map(|data| data.key)
        .filter(|key| !table.aliases.iter().any(|alias| alias.canonical == *key))
        .collect();
    let mut lines = vec![
        "# Generated input-alias coverage (2026-10-27)".to_string(),
        String::new(),
        "Generated by `kerotakis_core::species::input_alias_table()` and checked by".to_string(),
        "`crates/kerotakis-core/tests/input_alias_coverage.rs`. Do not edit by hand:".to_string(),
        "run that test with `KEROTAKIS_BLESS_ALIAS_COVERAGE=1` to regenerate.".to_string(),
        String::new(),
        format!("- Registry species: {}", registry.len()),
        format!(
            "- Species reachable by at least one alias: {}",
            registry.len() - missing.len()
        ),
        format!("- Accepted aliases: {}", table.aliases.len()),
        format!("- Refused alias spellings: {}", table.refused.len()),
        String::new(),
        "## Accepted aliases by source".to_string(),
        String::new(),
        "| source | count |".to_string(),
        "|---|---|".to_string(),
    ];
    for source in INPUT_ALIAS_SOURCES {
        if let Some(count) = counts.get(source).filter(|count| **count > 0) {
            lines.push(format!("| {source} | {count} |"));
        }
    }
    lines.extend([
        String::new(),
        "## Refused aliases".to_string(),
        String::new(),
        "| alias | candidates | reason |".to_string(),
        "|---|---|---|".to_string(),
    ]);
    let ticks = |items: &[String]| {
        items
            .iter()
            .map(|item| format!("`{item}`"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    for refused in &table.refused {
        lines.push(format!(
            "| {} | {} | {} |",
            ticks(&refused.spellings),
            ticks(&refused.candidates),
            refused.reason
        ));
    }
    lines.extend([
        String::new(),
        "## Species without any alias".to_string(),
        String::new(),
    ]);
    lines.extend(missing.iter().map(|key| format!("- `{key}`")));
    lines.extend([
        String::new(),
        "## Accepted aliases".to_string(),
        String::new(),
        "| alias | canonical | source |".to_string(),
        "|---|---|---|".to_string(),
    ]);
    for alias in &table.aliases {
        lines.push(format!(
            "| `{}` | `{}` | {} |",
            alias.alias, alias.canonical, alias.source
        ));
    }
    lines.join("\n") + "\n"
}

#[test]
fn generated_alias_table_matches_checked_in_fixture_and_doc() {
    let table = species::input_alias_table();
    let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let markdown = render_markdown(table);
    if std::env::var_os(BLESS).is_some() {
        std::fs::write(
            manifest.join(FIXTURE),
            serde_json::to_string_pretty(table).unwrap() + "\n",
        )
        .unwrap();
        std::fs::write(manifest.join(DOC), &markdown).unwrap();
    }
    let fixture: InputAliasTable =
        serde_json::from_str(&std::fs::read_to_string(manifest.join(FIXTURE)).unwrap()).unwrap();
    if &fixture != table {
        let stale: Vec<_> = fixture
            .aliases
            .iter()
            .filter(|alias| !table.aliases.contains(alias))
            .collect();
        let fresh: Vec<_> = table
            .aliases
            .iter()
            .filter(|alias| !fixture.aliases.contains(alias))
            .collect();
        panic!(
            "input-alias fixture is stale (rerun with {BLESS}=1 and review the diff).\n\
             only in fixture: {stale:?}\nonly generated: {fresh:?}\n\
             refused fixture/generated: {}/{}",
            fixture.refused.len(),
            table.refused.len()
        );
    }
    let doc = std::fs::read_to_string(manifest.join(DOC)).unwrap();
    assert_eq!(
        doc.replace("\r\n", "\n"),
        markdown,
        "docs/input-alias-coverage-20261027.md is stale (rerun with {BLESS}=1)"
    );
}

#[test]
fn every_curated_alias_survives_generation() {
    let table = species::input_alias_table();
    for &(alias, key) in CURATED {
        assert!(
            table
                .aliases
                .iter()
                .any(|entry| entry.alias == alias && entry.canonical == key),
            "curated {alias} -> {key} lost"
        );
        assert_eq!(species::lookup_key(alias).unwrap().key, key);
        assert_eq!(SpeciesId::new(alias), SpeciesId::new(key));
    }
}

#[test]
fn every_accepted_alias_resolves_uniquely_and_never_shadows_a_key() {
    let table = species::input_alias_table();
    let mut by_spelling: BTreeMap<String, &str> = BTreeMap::new();
    for entry in &table.aliases {
        assert!(INPUT_ALIAS_SOURCES.contains(&entry.source.as_str()));
        assert_eq!(
            species::lookup_key(&entry.alias).map(|data| data.key),
            Some(entry.canonical.as_str()),
            "{entry:?}"
        );
        assert!(
            species::registry()
                .iter()
                .all(|data| !data.key.eq_ignore_ascii_case(&entry.alias)),
            "{} hides a registry key",
            entry.alias
        );
        let normalized = entry
            .alias
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ")
            .to_lowercase();
        if let Some(previous) = by_spelling.insert(normalized, &entry.canonical) {
            assert_eq!(previous, entry.canonical, "{} is ambiguous", entry.alias);
        }
    }
    // Every refusal is a real refusal: none of its spellings resolve.
    for refused in &table.refused {
        if refused.reason == "curated-alias-wins" || refused.reason == "registry-key" {
            continue;
        }
        for spelling in &refused.spellings {
            assert!(
                species::lookup_key(spelling).is_none(),
                "refused {spelling} ({}) still resolves",
                refused.reason
            );
        }
    }
}

#[test]
fn shared_formulas_and_isomers_are_refused_not_guessed() {
    let table = species::input_alias_table();
    let reason = |spelling: &str| {
        table
            .refused
            .iter()
            .find(|refused| refused.spellings.iter().any(|s| s == spelling))
            .map(|refused| refused.reason.as_str())
    };
    // Two registry identities share each of these formulas.
    for formula in ["C2H4", "C6H12O6", "C12H22O11", "C6H10O5"] {
        assert_eq!(reason(formula), Some("ambiguous"), "{formula}");
        assert!(species::lookup_key(formula).is_none(), "{formula}");
    }
    // Hill formulas name compositions, not compounds.
    for formula in ["C3H8O", "C4H10O", "C3H6"] {
        assert_eq!(
            reason(formula),
            Some("isomer-ambiguous-formula"),
            "{formula}"
        );
        assert!(species::lookup_key(formula).is_none(), "{formula}");
    }
    // The qualifier is what tells charcoal from graphite and diamond.
    assert_eq!(reason("carbon"), Some("qualifier-required"));
    assert!(species::lookup_key("carbon").is_none());
    // A formula shared with distinct keys stays the key it already is.
    assert_eq!(species::lookup_key("CO2").unwrap().key, "CO2");
    assert_eq!(species::lookup_key("N2").unwrap().key, "N2");
    assert_ne!(SpeciesId::new("CO2"), SpeciesId::new("dry_ice"));
    assert_ne!(SpeciesId::new("N2"), SpeciesId::new("liquid_nitrogen"));
    // Material bottles keep their names.
    assert_eq!(reason("washing soda"), Some("material-name"));
}

#[test]
fn hydrate_and_anhydrous_spellings_stay_distinct_identities() {
    for spelling in ["CuSO4·5H2O", "CuSO4.5H2O", "CuSO4*5H2O"] {
        assert_eq!(species::lookup_key(spelling).unwrap().key, "chalcanthite");
        assert_ne!(SpeciesId::new(spelling), SpeciesId::new("CuSO4"));
    }
    assert_eq!(species::lookup_key("copper sulfate").unwrap().key, "CuSO4");
    assert_eq!(species::lookup_key("CuSO4_anhydrous").unwrap().key, "CuSO4");
    for spelling in ["MgSO4·7H2O", "MgSO4.7H2O", "MgSO4*7H2O"] {
        assert_eq!(species::lookup_key(spelling).unwrap().key, "epsomite");
        assert_ne!(SpeciesId::new(spelling), SpeciesId::new("MgSO4"));
    }
    assert_eq!(species::lookup_key("MgSO4_anhydrous").unwrap().key, "MgSO4");
    // No anhydrous spelling is invented where the registry has no hydrate pair.
    assert!(species::lookup_key("NaCl_anhydrous").is_none());
    assert!(species::lookup_key("CaSO4_anhydrous").is_none());
}

#[test]
fn ion_names_never_turn_an_element_into_its_ion() {
    assert_eq!(species::lookup_key("sulfate").unwrap().key, "SO4-2");
    assert_eq!(species::lookup_key("Sulfat").unwrap().key, "SO4-2");
    assert_eq!(species::lookup_key("chlorure").unwrap().key, "Cl-");
    assert_eq!(species::lookup_key("ammonium").unwrap().key, "NH4+");
    assert_eq!(species::lookup_key("Ca2+").unwrap().key, "Ca+2");
    assert_eq!(species::lookup_key("Cu+").unwrap().key, "Cu+1");
    // `sodium`, `calcium`, `hydrogen ion`'s stem: metals/molecules, not ions.
    assert!(species::lookup_key("sodium").is_none());
    assert!(species::lookup_key("calcium").is_none());
    assert_eq!(species::lookup_key("hydrogen").unwrap().key, "H2");
    assert_eq!(species::lookup_key("magnesium").unwrap().key, "Mg");
    // Ambiguous digit runs are not generated.
    assert!(species::lookup_key("SO42-").is_none());
    // Case is identity: only the registry's own spellings are aliases.
    assert!(species::lookup_key("Sodium chloride").is_none());
    assert!(species::lookup_key("SULFATE").is_none());
}

#[test]
fn generated_aliases_parse_to_the_canonical_operator() {
    for (alias, key) in [
        ("sulfate ion", "SO4-2"),
        ("Ca2+", "Ca+2"),
        ("CuSO4.5H2O", "chalcanthite"),
        ("potassium nitrate", "KNO3"),
        ("Kaliumnitrat", "KNO3"),
    ] {
        if species::lookup_key(alias).is_none() {
            // Translations are data; skip if a catalogue does not carry one.
            continue;
        }
        assert_eq!(
            parse_op(&format!("add v1 {alias} 0.001mol")).unwrap(),
            parse_op(&format!("add v1 {key} 0.001mol")).unwrap(),
            "{alias}"
        );
    }
}

#[test]
fn packs_cannot_install_a_species_under_a_generated_alias() {
    for alias in ["sulfate", "Ca2+", "CuSO4.5H2O", "copper sulfate"] {
        let mut data = species::lookup_key("NaCl").unwrap().clone();
        data.key = alias;
        assert_eq!(species::register_loaded(vec![data]), (0, 1), "{alias}");
    }
}
