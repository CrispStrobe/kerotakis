#!/usr/bin/env python3
"""Activity-model range coverage (2026-11-09).

Reads the cited validity table crates/kerotakis-phreeqc/data/
pitzer-electrolyte-ranges.json (the one the runtime `activity_range`
module includes) and, when the vendored pitzer.dat is available, checks
which electrolytes the shipped dataset can represent at all.

Every row is classified:

  ranged          a stated maximum molality; the Pitzer route refuses
                  activity-derived outputs past it
  no-stated-range answered as before, validity not claimed
  absent          an ion is not in pitzer.dat, so the route never admits it

Usage:
  python3 tools/activity_range_coverage.py [--database-dir DIR] [--check]

Writes docs/activity-model-range-coverage-20261109.{md,json}. `--check`
fails if the checked-in files differ. The Rust test
`activity_range_coverage_is_current` checks the runtime table against the
JSON.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "crates/kerotakis-phreeqc/data/pitzer-electrolyte-ranges.json"
OUT_MD = ROOT / "docs/activity-model-range-coverage-20261109.md"
OUT_JSON = ROOT / "docs/activity-model-range-coverage-20261109.json"
ION_ELEMENT = {"OH": None, "H": None}


def master_elements(dat: Path) -> set[str] | None:
    if not dat.is_file():
        return None
    text = dat.read_text(encoding="latin-1")
    block = text.split("SOLUTION_MASTER_SPECIES", 1)[1].split("SOLUTION_SPECIES", 1)[0]
    found = set()
    for line in block.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            found.add(re.split(r"\s+", line)[0].split("(")[0])
    return found


def build(database_dir: Path) -> dict:
    table = json.loads(TABLE.read_text(encoding="utf-8"))
    elements = master_elements(database_dir / "pitzer.dat")
    rows = []
    for row in table["electrolytes"]:
        if elements is not None:
            for ion in (row["cation"], row["anion"]):
                el = ION_ELEMENT.get(ion, ion)
                if el is not None and el not in elements:
                    raise SystemExit(f"{row['electrolyte']}: {el} not in pitzer.dat")
        rows.append({
            "electrolyte": row["electrolyte"],
            "class": "ranged" if row["max_molality"] is not None else "no-stated-range",
            "max_molality": row["max_molality"],
            "source": row["source"],
        })
    for row in table["absent_from_dataset"]:
        if elements is not None and row["missing"].split("(")[0] in elements and "(" not in row["missing"]:
            raise SystemExit(f"{row['electrolyte']}: {row['missing']} IS in pitzer.dat; move it to electrolytes")
        rows.append({
            "electrolyte": row["electrolyte"],
            "class": "absent",
            "max_molality": None,
            "source": f"pitzer.dat has no {row['missing']}",
        })
    counts = {c: sum(r["class"] == c for r in rows) for c in ("ranged", "no-stated-range", "absent")}
    return {"rows": rows, "counts": counts, "sources": table["sources"]}


def render_md(doc: dict) -> str:
    out = [
        "# Activity-model range coverage (2026-11-09)",
        "",
        "Generated by `tools/activity_range_coverage.py` from",
        "`crates/kerotakis-phreeqc/data/pitzer-electrolyte-ranges.json`; do not edit by hand.",
        "",
        "The Pitzer route (`pitzer.dat`) is chosen for concentrated brines, but its",
        "parameters are fitted per binary electrolyte to a stated molality. The shipped",
        "file states no ranges itself, so each comes from the primary fit. Past a stated",
        "range the solver withdraws pH, activities and saturation indices with",
        "`not-modeled.activity-model-outside-range` (EN/DE/FR); the inventory is kept and",
        "the pH meter reports the refusal. Composition rule (stoichiometric molality per",
        "cation-anion pair, strong H+/OH- excess net of weak-acid capacity) is documented in",
        "`crates/kerotakis-phreeqc/src/activity_range.rs`.",
        "",
        f"Counts: {doc['counts']['ranged']} ranged, {doc['counts']['no-stated-range']} no stated range, "
        f"{doc['counts']['absent']} absent from the dataset.",
        "",
        "| Electrolyte | Class | Max molality (mol/kg) | Source |",
        "|---|---|---|---|",
    ]
    for r in doc["rows"]:
        m = "" if r["max_molality"] is None else f"{r['max_molality']}"
        out.append(f"| {r['electrolyte']} | {r['class']} | {m} | {r['source']} |")
    out += ["", "## Sources", ""]
    for key, text in doc["sources"].items():
        out.append(f"- **{key}**: {text}")
    out += [
        "",
        "## Known limits",
        "",
        "- Only binary ranges are checked. A mixed brine whose every pair is inside its",
        "  range is answered, although mixing terms (theta, psi) carry their own fits.",
        "- Ranges are for 25 C; temperature dependence of the fitted range is not modelled.",
        "- `no-stated-range` rows keep their previous behaviour; the provenance sentence no",
        "  longer claims the model is valid at high ionic strength.",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--database-dir", type=Path, default=ROOT / "vendor/iphreeqc/database")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    doc = build(args.database_dir)
    js = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
    md = render_md(doc)
    if args.check:
        stale = [p.name for p, t in ((OUT_JSON, js), (OUT_MD, md))
                 if not p.is_file() or p.read_text(encoding="utf-8") != t]
        if stale:
            print(f"stale: {', '.join(stale)}; run python3 tools/activity_range_coverage.py", file=sys.stderr)
            return 1
        print("activity-model range coverage is current")
        return 0
    OUT_JSON.write_text(js, encoding="utf-8")
    OUT_MD.write_text(md, encoding="utf-8")
    print(f"wrote {OUT_JSON.relative_to(ROOT)} and {OUT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
