#!/usr/bin/env python3
"""Peroxide/iodide pathway-partition coverage (2026-11-11).

Reads CATALYST_PATHWAY_OWNERS and OWNER_MEASURED_PROTON_FLOOR from
crates/kerotakis-core/src/kinetics.rs and classifies, for every owned catalyst
branch, the acidity regimes the bench meets:

  owned-measured     represented acid, (H+) >= floor: owner rows run, measured law
  owned-extrapolated represented acid, (H+) <  floor: owner rows run, typed notice
                     not-modeled.pathway-owner-below-measured-acid
  unowned-refused    (H+) >= floor but no represented acid: catalysed branch runs,
                     typed notice not-modeled.catalyst-branch-acid-unowned
  neutral-catalysed  no represented acid, (H+) < floor: catalysed decomposition

`--check` fails when the checked-in docs are stale, when an owner row has no
measured floor, or when a typed notice key is missing from the DE/FR locales.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KINETICS = ROOT / "crates/kerotakis-core/src/kinetics.rs"
CLOCK = ROOT / "crates/kerotakis-core/src/clock.rs"
LOCALES = [ROOT / "crates/kerotakis-core/i18n/de.toml", ROOT / "crates/kerotakis-core/i18n/fr.toml"]
OUT_MD = ROOT / "docs/peroxide-iodide-acid-partition-coverage-20261111.md"
OUT_JSON = ROOT / "docs/peroxide-iodide-acid-partition-coverage-20261111.json"
KEYS = ["pathway-owner-below-measured-acid", "catalyst-branch-acid-unowned"]
SOURCE = ("Liebhafsky & Mohammad, J. Am. Chem. Soc. 55 (1933) 3977-3986, doi:10.1021/ja01337a010; "
          "archive.org scan of JACS vol. 55 (dli.ernet.233065), p. 3980 Table I Curve II: "
          "lowest 25 C (H+) = 7.62e-3 M ((H+) x 10^2 = 0.762 at (I-) = 0.0572), "
          "k'/(I-) = 0.770 = 0.69 + 10.4 x 0.00762")


def block(text: str, name: str) -> str:
    m = re.search(rf"const {name}[^=]*=\s*&\[(.*?)\n\];", text, re.S)
    if not m:
        sys.exit(f"{name} not found in kinetics.rs")
    return m.group(1)


def build() -> tuple[dict, list[str]]:
    src = KINETICS.read_text()
    owners = re.findall(r'\(\s*"([^"]+)",\s*"([^"]+)",\s*&\[([^\]]*)\],?\s*\)',
                        block(src, "CATALYST_PATHWAY_OWNERS"))
    floors = dict((r, float(f)) for r, f in re.findall(r'\("([^"]+)",\s*([0-9.eE+-]+)\)',
                                                        block(src, "OWNER_MEASURED_PROTON_FLOOR")))
    problems = []
    rows = []
    for reaction, catalyst, owner_list in owners:
        names = re.findall(r'"([^"]+)"', owner_list)
        for o in names:
            if o not in floors:
                problems.append(f"owner {o} has no measured proton floor")
        floor = min((floors[o] for o in names if o in floors), default=None)
        rows.append({
            "reaction": reaction, "catalyst": catalyst, "owners": names,
            "measured_proton_floor_molar": floor, "source": SOURCE,
            "regimes": {
                "owned-measured": "owner rows run on the measured law (iodine)",
                "owned-extrapolated": "owner rows run; typed notice " + KEYS[0],
                "unowned-refused": "catalysed O2 booked; typed notice " + KEYS[1],
                "neutral-catalysed": "catalysed decomposition (O2), measured outcome",
            },
        })
    clock = CLOCK.read_text()
    for key in KEYS:
        if f'"not-modeled.{key}"' not in clock:
            problems.append(f"clock.rs does not emit not-modeled.{key}")
        for loc in LOCALES:
            if not re.search(rf"^{re.escape(key)} = ", loc.read_text(), re.M):
                problems.append(f"{loc.name} lacks {key}")
    unsourced = [{
        "step": "HOI + H2O2 -> I- + O2 + H+ + H2O",
        "status": "refused-typed",
        "reason": "no rate constant read from a primary; below the measured acid floor the iodine/oxygen split "
                  "of the HOI intermediate is reported as an extrapolation instead of computed",
    }]
    return {"generated_by": "tools/peroxide_iodide_acid_partition_coverage.py", "rows": rows,
            "notice_keys": KEYS, "unsourced_steps": unsourced,
            "ki011": {"ph": 1.865065588166, "proton_molar": round(10 ** -1.865065588166, 6),
                      "regime": "owned-extrapolated"}}, problems


def render(data: dict) -> str:
    out = ["# Peroxide/iodide acid partition coverage (2026-11-11)", "",
           "Generated by `tools/peroxide_iodide_acid_partition_coverage.py --check`.", "",
           "One owner per elementary step: the iodide-catalysed branch of `peroxide-decomposition` stands",
           "down while a clock row can consume represented acid (CATALYST_PATHWAY_OWNERS, round-3 iodine-clock",
           "lane). This lane bounds that ownership by the acidity the owning law was measured at.", "",
           "| reaction | catalyst | owners | measured (H+) floor M | source |", "|---|---|---|---|---|"]
    for r in data["rows"]:
        out.append(f"| {r['reaction']} | {r['catalyst']} | {', '.join(r['owners'])} | "
                   f"{r['measured_proton_floor_molar']} | {r['source']} |")
    out += ["", "## Regimes", "", "| regime | behaviour |", "|---|---|"]
    for k, v in data["rows"][0]["regimes"].items():
        out.append(f"| {k} | {v} |")
    out += ["", "## Refused (typed)", "", "| step | status | reason |", "|---|---|---|"]
    for u in data["unsourced_steps"]:
        out.append(f"| {u['step']} | {u['status']} | {u['reason']} |")
    k = data["ki011"]
    out += ["", "## batch2:ki-011", "",
            f"pH {k['ph']} gives (H+) = {k['proton_molar']} M, below the measured floor: the clock rows own",
            "H2O2 + I- (no catalytic O2) and each interval carries the typed extrapolation notice.", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    data, problems = build()
    md, js = render(data), json.dumps(data, indent=2, sort_keys=True) + "\n"
    if args.check:
        if not OUT_MD.exists() or OUT_MD.read_text() != md:
            problems.append(f"{OUT_MD.name} stale")
        if not OUT_JSON.exists() or OUT_JSON.read_text() != js:
            problems.append(f"{OUT_JSON.name} stale")
        for p in problems:
            print("FAIL:", p)
        return 1 if problems else 0
    OUT_MD.write_text(md)
    OUT_JSON.write_text(js)
    for p in problems:
        print("FAIL:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
