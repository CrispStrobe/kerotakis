#!/usr/bin/env python3
"""Solid-vs-melt density coverage (th-004 round 4, 2026-11-11).

Whether a solid floats or sinks in its OWN melt needs two densities of one
substance. `phase_density::PHASE_DENSITY_PAIRS` carries sourced pairs;
everything else keeps the registry's single density for both phases (no
melt density is invented). This tool reads, from source:

  pairs       every row: species, solid/liquid density and temperatures,
              DOI present, and whether the solid sinks in its melt
  ranges      every `melting_range::MELTING_RANGES` material, and whether a
              pair covers it (a range material melts in the beaker, so it
              is the family this matters for)
  wiring      `buoyancy::floats_in` reads `density_in_phase(.., Solid)`;
              `buoyancy::liquid_density_g_per_ml` applies the pair's liquid
              density; `settle_range_melts` reports its transition clamped
              into the range
  tests       every test named in TESTS exists

Writes docs/phase-density-coverage-20261111.{md,json}; `--check` fails when
either is stale or a check fails.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "crates/kerotakis-core"
PAIRS = CORE / "src/phase_density.rs"
RANGES = CORE / "src/melting_range.rs"
BUOY = CORE / "src/buoyancy.rs"
TEST = CORE / "tests/paraffin_melt_density.rs"
MD = ROOT / "docs/phase-density-coverage-20261111.md"
JS = ROOT / "docs/phase-density-coverage-20261111.json"
TESTS = [
    "paraffin_pair_is_sourced_and_denser_as_a_solid",
    "molten_paraffin_has_its_sourced_liquid_density",
    "solid_paraffin_sinks_in_its_own_melt",
    "solid_paraffin_still_floats_on_water",
    "a_species_without_a_pair_keeps_its_registry_density",
    "th004_freezing_on_cooling_is_reported_inside_the_declared_range",
    "melting_inside_the_range_is_reported_at_the_vessel_temperature",
]


def num(b, field):
    return float(re.search(field + r": ([\d_.]+),", b).group(1).replace("_", ""))


def pairs():
    src = PAIRS.read_text(encoding="utf-8").split("#[cfg(test)]")[0]
    start = src.index("pub const PHASE_DENSITY_PAIRS")
    body = src[start:src.index("}];", start) + 2]
    rows = []
    for m in re.finditer(r"PhaseDensityPair \{(.*?)\n\s*\}", body, re.S):
        b = m.group(1)
        rows.append(dict(
            species=re.search(r'species: "([^"]+)"', b).group(1),
            solid_g_per_ml=num(b, "solid_g_per_ml"), solid_at_c=num(b, "solid_at_c"),
            liquid_g_per_ml=num(b, "liquid_g_per_ml"), liquid_at_c=num(b, "liquid_at_c"),
            source=re.search(r'source: "([^"]+)"', b).group(1),
        ))
    return rows


def range_species():
    src = RANGES.read_text(encoding="utf-8")
    body = src[src.index("pub const MELTING_RANGES"):]
    body = body[:body.index("];")]
    return re.findall(r'species: "([^"]+)"', body)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rows = pairs()
    problems = []
    for r in rows:
        r["solid_sinks_in_melt"] = r["solid_g_per_ml"] > r["liquid_g_per_ml"]
        if "doi:" not in r["source"]:
            problems.append(f"{r['species']}: no DOI")
    covered = {r["species"] for r in rows}
    ranges = [dict(species=s, pair=s in covered) for s in range_species()]
    buoy = BUOY.read_text(encoding="utf-8")
    melt = RANGES.read_text(encoding="utf-8")
    wiring = {
        "floats_in reads the solid-phase density": "density_in_phase(species, crate::species::Phase::Solid)" in re.sub(r"\s+", " ", buoy).replace("( ", "(").replace(" )", ")") or "Phase::Solid)?" in buoy,
        "liquid density applies the pair's melt density": "phase_density::pair(" in buoy and "pair.liquid_g_per_ml" in buoy,
        "range transition event clamped into the range": "t1.clamp(" in melt,
    }
    problems += [f"wiring: {k}" for k, ok in wiring.items() if not ok]
    test_src = TEST.read_text(encoding="utf-8") if TEST.exists() else ""
    problems += [f"missing test {t}" for t in TESTS if f"fn {t}(" not in test_src]

    data = dict(generated_by="tools/phase_density_coverage.py", pairs=rows,
                range_materials=ranges, wiring=wiring, tests=TESTS)
    md = ["# Solid-vs-melt density coverage (2026-11-11)", "",
          "Generated by `tools/phase_density_coverage.py --check`.", "",
          "**Rule.** A solid in its own melt is compared at two sourced densities of the same",
          "substance (`phase_density::PHASE_DENSITY_PAIRS`): `buoyancy::floats_in` reads the solid's",
          "density for the solid phase and `buoyancy::liquid_density_g_per_ml` counts the melt at its",
          "sourced liquid density. Without a pair both phases keep the registry's single density;",
          "no melt density is invented. A melting-range material's `state_changed` event is reported",
          "at the vessel temperature clamped into the declared range, so wax cooled to 20 °C is",
          "reported to finish freezing at the bottom of its range, not at 20 °C.", "",
          "## Sourced pairs", "",
          "| species | solid (g/mL @ °C) | liquid (g/mL @ °C) | solid sinks in melt | source |",
          "|---|---|---|---|---|"]
    md += [f"| {r['species']} | {r['solid_g_per_ml']} @ {r['solid_at_c']} | {r['liquid_g_per_ml']} @ {r['liquid_at_c']} | "
           f"{'yes' if r['solid_sinks_in_melt'] else 'no'} | {r['source']} |" for r in rows]
    md += ["", "## Melting-range materials", "", "| species | sourced pair |", "|---|---|"]
    md += [f"| {r['species']} | {'yes' if r['pair'] else 'no — registry density for both phases'} |" for r in ranges]
    md += ["", "## Wiring", ""]
    md += [f"- {k}: {'ok' if v else 'MISSING'}" for k, v in wiring.items()]
    md += ["", "## Notes", "",
           "- Paraffin's pair is manufacturer data for one technical grade (RT58, 53-59 °C) as tabulated",
           "  by Gasia et al. (2016); the bench's paraffin is the span of grades in Sharma et al. (2009).",
           "  The pair is used for the sign of solid-vs-melt buoyancy and the melt's volume, not as a",
           "  temperature-dependent density.",
           "- PE and PP melts are refused (no payable latent heat), so no PE/PP melt arises to compare.",
           "", "## Tests", ""]
    md += [f"- `crates/kerotakis-core/tests/paraffin_melt_density.rs::{t}`" for t in TESTS]
    md.append("")
    text = "\n".join(md)
    js = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    if a.check:
        bad = bool(problems)
        for p in problems:
            print("problem:", p, file=sys.stderr)
        for path, want in ((MD, text), (JS, js)):
            if not path.exists() or path.read_text(encoding="utf-8") != want:
                print("stale:", path, file=sys.stderr)
                bad = True
        return 1 if bad else 0
    MD.write_text(text, encoding="utf-8")
    JS.write_text(js, encoding="utf-8")
    print(json.dumps({"pairs": len(rows), "problems": problems}))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
