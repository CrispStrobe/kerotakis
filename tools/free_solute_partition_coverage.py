#!/usr/bin/env python3
"""Free-solute partition coverage (2026-11-11, SP-011).

A liquid/liquid distribution coefficient is the ratio of the FREE neutral
solute in the two phases. Reads `PARTITION_COEFFICIENTS` and
`AQUEOUS_ONLY_COMPLEXES` from crates/kerotakis-core/src/apparatus.rs and
classifies every reviewed partition row:

  free-solute        the solute has an aqueous-only complex row; only the free
                     share partitions and the complex re-equilibrates after
                     every stage (`apparatus::extract_free_solute`)
  plain              no aqueous-only complex is reviewed for this solute; the
                     coefficient acts on the dissolved analytical amount

Complex rows outside their temperature window, or with an undissolved solid
reservoir, are refused with `not-modeled.aqueous-complex-temperature` /
`not-modeled.aqueous-complex-with-solid` (EN/DE/FR). Every complex row must
name a solute that has a partition row and a doi.

Writes docs/free-solute-partition-coverage-20261111.{md,json}; `--check`
fails when stale or when a row is invalid.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "crates/kerotakis-core/src/apparatus.rs"
MD = ROOT / "docs/free-solute-partition-coverage-20261111.md"
JS = ROOT / "docs/free-solute-partition-coverage-20261111.json"
LOCALES = [ROOT / "crates/kerotakis-core/i18n/de.toml", ROOT / "crates/kerotakis-core/i18n/fr.toml"]
KEYS = ["aqueous-complex-temperature", "aqueous-complex-with-solid"]


def block(src: str, name: str) -> str:
    i = src.index(f"pub const {name}")
    return src[i:src.index("}];", i)]


def field(b: str, key: str) -> str | None:
    m = re.search(rf'\b{key}: "((?:[^"\\]|\\.)*)"', b) or re.search(rf'\b{key}: ([^,\n]+),', b)
    return m.group(1).strip() if m else None


def rows(src: str, name: str, struct: str):
    out = []
    for part in block(src, name).split(f"{struct} {{")[1:]:
        out.append({k: field(part, k) for k in (
            "solute", "organic_solvent", "aqueous_solvent", "k_organic_over_aqueous",
            "ligand", "complex", "association_k_l_per_mol", "reference_temperature_k",
            "temperature_tolerance_k", "source") if field(part, k) is not None})
    return out


def build():
    src = SRC.read_text(encoding="utf-8").split("#[cfg(test)]")[0]
    parts = rows(src, "PARTITION_COEFFICIENTS", "PartitionCoefficient")
    cplx = rows(src, "AQUEOUS_ONLY_COMPLEXES", "AqueousOnlyComplex")
    errors = []
    for c in cplx:
        ref = re.fullmatch(r"crate::(\w+)::(\w+)", c.get("association_k_l_per_mol") or "")
        if ref:
            mod = (ROOT / f"crates/kerotakis-core/src/{ref.group(1)}.rs").read_text(encoding="utf-8")
            m = re.search(rf"pub const {ref.group(2)}: f64 = ([\d._]+);", mod)
            c["association_k_l_per_mol"] = m.group(1).replace("_", "") if m else None
        if not c.get("association_k_l_per_mol"):
            errors.append(f"complex row {c['solute']} has no readable association constant")
        if not any(p["solute"] == c["solute"] for p in parts):
            errors.append(f"complex row {c['solute']} has no partition row")
        if "doi:" not in (c.get("source") or ""):
            errors.append(f"complex row {c['solute']} cites no doi")
    for f in LOCALES:
        text = f.read_text(encoding="utf-8")
        for k in KEYS:
            if not re.search(rf"^{re.escape(k)} = ", text, re.M):
                errors.append(f"{f.name} lacks not-modeled.{k}")
    table = []
    for p in parts:
        c = next((c for c in cplx if c["solute"] == p["solute"]), None)
        table.append({
            "solute": p["solute"],
            "pair": f"{p['organic_solvent']}/{p['aqueous_solvent']}",
            "k_d": p["k_organic_over_aqueous"],
            "class": "free-solute" if c else "plain",
            "complex": f"{c['complex']} (with {c['ligand']}, K = {c['association_k_l_per_mol']})" if c else None,
            "complex_source": c["source"] if c else None,
            "k_d_source": p["source"],
        })
    return {"partition_rows": table, "refusal_keys": [f"not-modeled.{k}" for k in KEYS]}, errors


def render(data) -> str:
    lines = [
        "# Free-solute partition coverage (2026-11-11)",
        "",
        "Generated by `tools/free_solute_partition_coverage.py`; `--check` holds it.",
        "",
        "A distribution coefficient K_D relates the FREE neutral solute in the two",
        "liquid phases. Where the solute also forms a complex that exists only in",
        "the water (I2 + I- <=> I3-), the engine distributes only the free share",
        "and re-equilibrates the complex after every stage",
        "(`apparatus::extract_free_solute`). SP-011: iodide-containing water now",
        "yields less iodine to hexane than iodide-free water.",
        "",
        "| solute | pair | K_D | class | aqueous-only complex | complex source |",
        "|---|---|---|---|---|---|",
    ]
    for r in data["partition_rows"]:
        lines.append(f"| {r['solute']} | {r['pair']} | {r['k_d']} | {r['class']} | {r['complex'] or '—'} | {r['complex_source'] or '—'} |")
    lines += ["", "K_D sources (unchanged by this lane):", ""]
    for r in data["partition_rows"]:
        lines.append(f"- {r['solute']} {r['pair']}: {r['k_d_source']}")
    lines += [
        "",
        "Typed refusals (EN in code, DE/FR in crates/kerotakis-core/i18n): "
        + ", ".join(f"`{k}`" for k in data["refusal_keys"]) + ".",
        "",
        "Open data gap: the I2 hexane/water K_D = 85 row predates this lane and cites a",
        "teaching exam question, not a primary measurement; a patent bench measurement",
        "(US 6,398,961) and lab handouts report about 35 for hexane, and 85 is the",
        "classic CCl4/water value. No primary hexane or CCl4 number could be read",
        "openly (Davies & Gwynne-type JACS papers, doi:10.1021/ja01562a008, are",
        "paywalled), so no K_D row was added or changed here. The 2026-11-11",
        "non-aqueous-solution lane searched again (see",
        "docs/nonaqueous-solution-coverage-20261111.md); the only primary alkane",
        "value found is K = 80 for cyclohexane / 1.00 F H2SO4 (Van de Steeg 1968,",
        "doi:10.2172/4770773), which is neither hexane nor pure water.",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    data, errors = build()
    md, js = render(data), json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if a.check:
        stale = [p.name for p, t in ((MD, md), (JS, js)) if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            print("stale: " + ", ".join(stale) + " (run tools/free_solute_partition_coverage.py)", file=sys.stderr)
            return 1
        print("free-solute partition coverage: up to date")
        return 0
    MD.write_text(md, encoding="utf-8")
    JS.write_text(js, encoding="utf-8")
    print(f"wrote {MD.name}, {JS.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
