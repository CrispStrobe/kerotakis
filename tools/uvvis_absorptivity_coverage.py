#!/usr/bin/env python3
"""UV-vis cited molar absorptivity coverage (2026-11-11, lane F).

Reads `crates/kerotakis-core/src/uvvis_absorptivity.rs` (TABLE, NO_DATA and
the source constants) and writes docs/uvvis-absorptivity-coverage-20261111.{md,json}.
`--check` fails when they are stale. The Rust test
`uvvis_absorptivity_coverage_is_current` holds the runtime table to the JSON.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "crates/kerotakis-core/src/uvvis_absorptivity.rs"
OUT_JS = ROOT / "docs/uvvis-absorptivity-coverage-20261111.json"
OUT_MD = ROOT / "docs/uvvis-absorptivity-coverage-20261111.md"


def rust_str(body: str) -> str:
    # Concatenate a Rust string literal with `\` line continuations.
    body = re.sub(r"\\\n\s*", "", body)
    return body.replace('\\"', '"')


def parse(src: str):
    consts = {m.group(1): rust_str(m.group(2)) for m in
              re.finditer(r'const ([A-Z0-9_]+): &str = "((?:[^"\\]|\\.)*)";', src, re.S)}
    table = src.split("pub const TABLE")[1].split("];")[0]
    rows = []
    for block in re.findall(r"CitedAbsorptivity \{(.*?)\n    \}", table, re.S):
        block = block + "\n"

        def field(name):
            m = re.search(rf"\b{name}: (.*?),\n", block, re.S)
            return m.group(1).strip()
        temp = field("temperature")
        t = None
        if temp != "None":
            t = [float(x) for x in re.findall(r"-?[0-9.]+", temp)]
        carriers = re.findall(r'\("([^"]+)", ([0-9.]+)\)', field("carriers"))
        rows.append({
            "species": field("species").strip('"'),
            "nm": float(field("nm")),
            "epsilon": float(field("epsilon")),
            "temperature": t,
            "carriers": [c for c, _ in carriers],
            "confidence": field("confidence").split("::")[1].lower(),
            "source": consts[field("source")],
        })
    nd = src.split("pub const NO_DATA")[1].split("];")[0]
    no_data = [{"species": a, "reason": rust_str(b)} for a, b in
               re.findall(r'\(\s*"([^"]+)",\s*"((?:[^"\\]|\\.)*)",\s*\)', nd, re.S)]
    return rows, no_data


def render(rows, no_data):
    species = sorted({r["species"] for r in rows})
    doc = {
        "generated_by": "tools/uvvis_absorptivity_coverage.py",
        "mechanism": "A(lambda) = l * sum eps(species, lambda, T) * c(species) over every species "
                     "with a cited row within 1 nm; any present absorber without a cited row at "
                     "that wavelength (or outside a row's temperature range) blocks the reading "
                     "with not-modeled.uvvis-absorptivity-no-data (EN/DE/FR)",
        "counts": {"rows": len(rows), "covered_species": len(species),
                   "refused_species": len(no_data),
                   "lower_confidence_rows": sum(r["confidence"] == "snippet" for r in rows)},
        "rows": rows,
        "no_data": no_data,
    }
    md = ["# UV-vis cited molar absorptivity coverage (2026-11-11)", "",
          "Generated by `tools/uvvis_absorptivity_coverage.py` from",
          "`crates/kerotakis-core/src/uvvis_absorptivity.rs`; `--check` and the Rust test",
          "`uvvis_absorptivity_coverage_is_current` hold it current.", "",
          "The spectrophotometer reports, besides its 16-band peak reading, one",
          "`absorbance at <λ> nm (cited molar absorptivity)` reading per analytical wavelength of",
          "every present species with a cited row: Beer–Lambert summed over all cited species at",
          "that wavelength (±1 nm), ε corrected for temperature where the source measured a",
          "coefficient. Anything present that could absorb there without a cited ε (another cited",
          "species without a row at λ, a coloured registry species without reviewed ε, a",
          "16-band registry spectrum, the starch–iodine complex, a `no_data` species, an unsolved",
          "Br2/Br⁻ association, a temperature outside the measured range) refuses that",
          "wavelength with `not-modeled.uvvis-absorptivity-no-data` (EN/DE/FR).", "",
          f"Counts: {len(rows)} rows, {len(species)} covered species, {len(no_data)} refused "
          f"species, {doc['counts']['lower_confidence_rows']} lower-confidence (snippet) rows.", "",
          "Confidence: `read` = number read in the cited document; `quoted` = read in a secondary "
          "naming the primary; `snippet` = only a quotation was read (lower confidence).", "",
          "| species | λ nm | ε L/mol/cm | T coefficient (per °C, range) | confidence | source |",
          "|---|---|---|---|---|---|"]
    for r in rows:
        t = "—" if r["temperature"] is None else \
            f"{r['temperature'][0] * 100:+.2f} %/°C, {r['temperature'][1]:.0f}–{r['temperature'][2]:.0f} °C"
        md.append(f"| {r['species']} | {r['nm']:g} | {r['epsilon']:g} | {t} | {r['confidence']} | "
                  f"{r['source']} |")
    md += ["", "## Refused (no sourced ε)", "", "| species | reason |", "|---|---|"]
    md += [f"| {d['species']} | {d['reason']} |" for d in no_data]
    md += ["", "The starch–iodine complex is refused as before (no reliable ε exists; see",
           "docs/starch-amylase-coverage-20261111.md).", "",
           "MnO4⁻: the registry's 16-band colour spectrum is scaled to the same 3340 at 525 nm",
           "(shape kept), so the band-peak reading and the cited 525 nm reading agree",
           "(`permanganate_band_peak_and_cited_525_reading_agree`). At 545 nm the scaled band gives",
           "about 3092 against the cited 3220 (4 %), a band-shape difference, not a second value.", ""]
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n", "\n".join(md)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rows, no_data = parse(SRC.read_text(encoding="utf-8"))
    if not rows or not no_data:
        print("uvvis coverage: could not parse TABLE / NO_DATA", file=sys.stderr)
        return 1
    js, md = render(rows, no_data)
    if a.check:
        stale = [p for p, t in ((OUT_JS, js), (OUT_MD, md))
                 if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            print("stale: " + ", ".join(str(p.relative_to(ROOT)) for p in stale)
                  + " (run python3 tools/uvvis_absorptivity_coverage.py)", file=sys.stderr)
            return 1
        print(f"uvvis absorptivity coverage current: {len(rows)} rows, {len(no_data)} refused")
        return 0
    OUT_JS.write_text(js, encoding="utf-8")
    OUT_MD.write_text(md, encoding="utf-8")
    print(f"wrote {OUT_JS.relative_to(ROOT)} and {OUT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
