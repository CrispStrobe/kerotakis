#!/usr/bin/env python3
"""Chromophore coverage audit for the spectrophotometer (2026-10-27).

Classifies EVERY registry species with the same rule as
`kerotakis_core::solution_optics::chromophore_class`:

  parameterised_ph      key in the indicator / pigment-ladder tables
  parameterised         registry spectrum present
  missing_absorptivity  curated appearance names a colour word and no
                        transparent word, no spectrum
                        -> the spectrophotometer refuses (typed not-modelled)
  outside_method        curated appearance colourless/white/clear/translucent
  unclassified          no curated appearance

Writes docs/chromophore-coverage-20261027.{md,json}; `--check` fails when
they are stale. The Rust test `chromophore_coverage_is_current` holds the
runtime classification to the JSON.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TRANSPARENT = ["colourless", "colorless", "white", "clear", "translucent"]
COLOURS = ["black", "grey", "gray", "silver", "red", "orange", "yellow", "green", "blue",
           "violet", "purple", "pink", "brown"]


def indicator_keys():
    src = (ROOT / "crates/kerotakis-core/src/indicator.rs").read_text()
    src = src.split("#[cfg(test)]")[0]
    return set(re.findall(r'\bkey:\s*"([^"]+)"', src))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    reg = json.loads((ROOT / "data/registry/registry-source-v1.json").read_text())
    optical = {o["species_id"]: o for o in reg["optical"]}
    ph = indicator_keys()
    rows = []
    for ident in reg["identities"]:
        key = ident["id"]
        o = optical.get(key)
        appearance = o["appearance"] if o else None
        spectrum = bool(o and o["spectrum"])
        if key in ph:
            cls = "parameterised_ph"
        elif spectrum:
            cls = "parameterised"
        elif appearance is None:
            cls = "unclassified"
        elif any(w in appearance.lower() for w in COLOURS) and not any(
                w in appearance.lower() for w in TRANSPARENT):
            cls = "missing_absorptivity"
        else:
            cls = "outside_method"
        rows.append(dict(species=key, appearance=appearance, class_=cls))
    rows.sort(key=lambda r: (r["class_"], r["species"]))
    counts = {}
    for r in rows:
        counts[r["class_"]] = counts.get(r["class_"], 0) + 1
    doc = dict(schema="kerotakis.chromophore-coverage.v1", transparent_words=TRANSPARENT, colour_words=COLOURS,
               counts=dict(sorted(counts.items())),
               species=[dict(species=r["species"], appearance=r["appearance"], **{"class": r["class_"]}) for r in rows])
    js = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
    md = ["# Chromophore coverage of the spectrophotometer (2026-10-27)", "",
          "Generated by `tools/chromophore_coverage.py` from the registry source document and the",
          "indicator tables. `chromophore_coverage_is_current` fails when the runtime disagrees.", "",
          "A vessel holding any dissolved/liquid `missing_absorptivity` species is REFUSED by the",
          "spectrophotometer (`not-modeled.unreviewed-molar-absorptivity`, EN/DE/FR) instead of",
          "reading 0 — the defect seen for iodine at 405 nm in QA-007, KI-011 and RX-007.",
          "Parameterised species keep their Beer–Lambert values. `unclassified` species have no",
          "curated appearance and are assumed non-absorbing in the visible; that assumption is",
          "listed here rather than hidden.", "",
          "The refusal is the spectrophotometer's half of the shared instrument coverage disclosure",
          "(`instrument_coverage::InstrumentCoverage`: supported / missing parameters / outside",
          "method); `instrument_coverage::disclosure_of` enumerates every instrument's status.", "",
          f"Counts: {', '.join(f'{k} {v}' for k, v in doc['counts'].items())}.", "",
          "| class | species | curated appearance |", "|---|---|---|"]
    for r in rows:
        md.append(f"| {r['class_']} | {r['species']} | {r['appearance'] or '—'} |")
    mdtext = "\n".join(md) + "\n"
    out_js = ROOT / "docs/chromophore-coverage-20261027.json"
    out_md = ROOT / "docs/chromophore-coverage-20261027.md"
    if a.check:
        bad = [p for p, t in ((out_js, js), (out_md, mdtext)) if not p.exists() or p.read_text() != t]
        if bad:
            print("stale:", *bad, file=sys.stderr)
            return 1
        return 0
    out_js.write_text(js)
    out_md.write_text(mdtext)
    print(json.dumps(doc["counts"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
