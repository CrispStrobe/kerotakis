#!/usr/bin/env python3
"""Stocking-phase coverage: which phase `add` deposits each reagent in (2026-11-09).

Classifies EVERY registry species with the same rule as
`kerotakis_core::phase_route::stocking_basis` / `stocked_phase`:

  derived                             sourced melting point AND a fusion owner
                                      (a FUSION_ENTHALPIES row, or water, whose
                                      ice solve::StateEquilibrator owns): the
                                      deposit phase is solid below the melting
                                      point and liquid above it
  melting_point_without_latent_heat   melting point sourced, no latent heat:
                                      standard_phase is used, because a solid
                                      the fusion ledger cannot pay to melt
                                      would stay solid for ever
  no_melting_point                    standard_phase is used
  not_condensed                       gas, aqueous, or a condensed gas (which
                                      arrives at its own transition point)

Writes docs/stocking-phase-coverage-20261109.{md,json}; `--check` fails when
they are stale. The Rust test `stocking_phase_coverage_is_current` holds the
runtime classification and the stocked phases to the JSON.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# The temperatures the table reports the stocked phase at: a cold room,
# the bench default, a warm one.
PROBES_C = [10.0, 25.0, 40.0]


def fusion_owners():
    src = (ROOT / "crates/kerotakis-core/src/phase_route.rs").read_text(encoding="utf-8")
    table = src.split("pub const FUSION_ENTHALPIES")[1].split("\n];")[0]
    return set(re.findall(r'species:\s*"([^"]+)"', table))


def prop(record):
    p = record["property"]
    return p if isinstance(p, str) else p.get("other")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    reg = json.loads((ROOT / "data/registry/registry-source-v1.json").read_text(encoding="utf-8"))
    owners = fusion_owners()
    props = {}
    for r in reg["phase_thermodynamics"]:
        props.setdefault(r["species_id"], {})[prop(r)] = r
    formula = {c["species_id"]: c["formula"] for c in reg["compositions"]}
    phase = {k: v["molar_mass"]["phase"] for k, v in props.items() if "molar_mass" in v}
    gas_formulas = {}
    for key, ph in phase.items():
        if ph == "gas":
            gas_formulas.setdefault(formula.get(key), set()).add(key)

    rows = []
    for ident in reg["identities"]:
        key = ident["id"]
        p = props.get(key, {})
        standard = phase.get(key)
        mp = p.get("melting_temperature", {}).get("quantity", {}).get("value")
        bp = p.get("boiling_temperature", {}).get("quantity", {}).get("value")
        condensed_gas = bool(gas_formulas.get(formula.get(key), set()) - {key})
        if standard not in ("solid", "liquid") or condensed_gas:
            basis = "not_condensed"
        elif mp is None:
            basis = "no_melting_point"
        elif key in owners or key == "water":
            basis = "derived"
        else:
            basis = "melting_point_without_latent_heat"
        stocked = {}
        for c in PROBES_C:
            t = round(c + 273.15, 10)
            if basis != "derived":
                stocked[f"{c:g}C"] = standard
            elif t < mp:
                stocked[f"{c:g}C"] = "solid"
            elif t > mp:
                stocked[f"{c:g}C"] = "liquid"
            else:
                stocked[f"{c:g}C"] = standard
        rows.append(dict(species=key, standard_phase=standard, melting_k=mp, boiling_k=bp,
                         fusion_owner=key in owners or key == "water", basis=basis,
                         stocked=stocked))
    rows.sort(key=lambda r: (r["basis"], r["species"]))
    counts = {}
    for r in rows:
        counts[r["basis"]] = counts.get(r["basis"], 0) + 1
    doc = dict(schema="kerotakis.stocking-phase-coverage.v1", probes_c=PROBES_C,
               counts=dict(sorted(counts.items())), species=rows)
    js = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
    fmt = lambda v: "—" if v is None else f"{v:g}"
    md = ["# Stocking-phase coverage of `add` (2026-11-09)", "",
          "Generated by `tools/stocking_phase_coverage.py` from the registry source document and",
          "`phase_route::FUSION_ENTHALPIES`. `stocking_phase_coverage_is_current` fails when the",
          "runtime disagrees.", "",
          "`add` deposits a reagent in the phase its own sourced melting point gives at the",
          "temperature it arrives at (`phase_route::stocked_phase`), not its 25 °C",
          "`standard_phase`. That derivation needs a fusion owner as well as a melting point,",
          "because a solid the fusion ledger cannot pay to melt would stay solid for ever; species",
          "with a melting point but no latent heat keep `standard_phase` and are listed here as",
          "the data gap they are. A liquid arriving above its boiling point is deposited liquid",
          "and boiled, with its latent heat paid, by the vaporising route.", "",
          "After a non-burning `ignite`, whatever the flame melted is refrozen when the vessel is",
          "put back at its starting temperature (`phase_route::refreeze_flame_melts`).", "",
          f"Counts: {', '.join(f'{k} {v}' for k, v in doc['counts'].items())}.", "",
          "| basis | species | standard | mp / K | bp / K | fusion owner | 10 °C | 25 °C | 40 °C |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        s = r["stocked"]
        md.append(f"| {r['basis']} | {r['species']} | {r['standard_phase'] or '—'} | {fmt(r['melting_k'])} "
                  f"| {fmt(r['boiling_k'])} | {'yes' if r['fusion_owner'] else 'no'} "
                  f"| {s['10C']} | {s['25C']} | {s['40C']} |")
    mdtext = "\n".join(md) + "\n"
    out_js = ROOT / "docs/stocking-phase-coverage-20261109.json"
    out_md = ROOT / "docs/stocking-phase-coverage-20261109.md"
    if a.check:
        bad = [p for p, t in ((out_js, js), (out_md, mdtext)) if not p.exists() or p.read_text(encoding="utf-8") != t]
        if bad:
            print("stale:", *bad, file=sys.stderr)
            return 1
        return 0
    out_js.write_text(js, encoding="utf-8")
    out_md.write_text(mdtext, encoding="utf-8")
    print(json.dumps(doc["counts"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
