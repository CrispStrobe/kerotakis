#!/usr/bin/env python3
"""Iodine-observable coverage of `extract` and the iodine-lane refusals (2026-11-11).

Classifies every registry species for a hexane/water `extract`:

  partitions        a reviewed distribution coefficient (docs/separation-coverage-20261109.json)
  ion-stays-aqueous charged species (PHREEQC charge suffix, same rule as
                    `conductivity::ion_charge`): kept in the water and named by
                    `not-modeled.extraction-ions-stay-aqueous`; an ion-only feed
                    is still extracted (solvent dispensed, nothing transferred)
  neutral-refused   neutral without a coefficient: `not-modeled.no-distribution-coefficient`
                    when nothing else partitions, else named beside the moved solutes

and records the reviewed status of the three iodine-lane observables.
Writes docs/iodine-observables-coverage-20261111.{md,json}; `--check` fails when stale.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_MD = ROOT / "docs/iodine-observables-coverage-20261111.md"
OUT_JSON = ROOT / "docs/iodine-observables-coverage-20261111.json"

CASES = [
    {
        "id": "new120:sp-011",
        "observable": "hexane extraction of a thiosulfate-reduced iodine feed",
        "status": "fixed",
        "mechanism": "ion-only feeds are extracted: hexane dispensed, ions kept aqueous and named "
                     "(not-modeled.extraction-ions-stay-aqueous, EN/DE/FR); residual I2, if any, "
                     "partitions with the existing reviewed K = 85 row",
        "tests": ["separation_receivers::ions_alone_are_extracted_as_nothing_and_kept_in_the_water",
                  "separation_receivers::ions_beside_an_unparameterised_neutral_still_refuse_and_dispense_nothing"],
    },
    {
        "id": "batch2:ki-011",
        "observable": "iodine-clock delay vs thiosulfate sink within 100 s; UV-vis with colloidal sulfur",
        "status": "refusal-kept; kinetics data gap recorded",
        "mechanism": "UV-vis refusal for sulfur (not-modeled.unreviewed-molar-absorptivity) is kept: "
                     "colloidal sulfur scatters and no reviewed extinction exists. The clock row "
                     "`iodide-peroxide-clock` uses an editorial pre-exponential (single [H+]-first-order term); "
                     "the primary two-term law of Liebhafsky & Mohammad, J. Am. Chem. Soc. 55 (1933) "
                     "3977-3986, doi:10.1021/ja01337a010 could not be read to transcribe its constants, so no "
                     "number was changed. The iodide-catalysed `peroxide-decomposition` catalyst row shares "
                     "the H2O2 + I- rate-determining step and is not suppressed in acid; it removes about half "
                     "the peroxide in 100 s here and slows the clock. Both need the primary constants.",
        "tests": [],
    },
    {
        "id": "batch3-diverse:en-001",
        "observable": "starch-triiodide absorbance; amylase digestion over the wait",
        "status": "refusal-kept; enzyme-rate data gap recorded",
        "mechanism": "not-modeled.starch-iodine-absorptivity kept: no primary molar absorptivity for the "
                     "amylose-triiodide complex could be sourced and verified. Amylase hydrolysis is a "
                     "curated instantaneous reaction; a Michaelis-Menten route needs a cited kcat/Km "
                     "for the enzyme preparation, not available, so it is recorded rather than tuned.",
        "tests": [],
    },
]


def ion_charge(name: str) -> int:
    m = re.search(r"([+-]+)(\d*)$", name.strip())
    if not m:
        return 0
    sign = 1 if m.group(1)[0] == "+" else -1
    return sign * (int(m.group(2)) if m.group(2) else len(m.group(1)))


def build():
    sep = json.loads((ROOT / "docs/separation-coverage-20261109.json").read_text(encoding="utf-8"))
    basis = {r["species"]: (r["extract_hexane"] or {}).get("basis") for r in sep["species"]}
    reg = json.loads((ROOT / "data/registry/registry-source-v1.json").read_text(encoding="utf-8"))
    rows = []
    for c in reg["compositions"]:
        sid = c["species_id"]
        if basis.get(sid):
            cls = "partitions"
        elif ion_charge(sid) != 0:
            cls = "ion-stays-aqueous"
        else:
            cls = "neutral-refused"
        rows.append({"species": sid, "class": cls, "basis": basis.get(sid)})
    rows.sort(key=lambda r: (r["class"], r["species"]))
    counts = {}
    for r in rows:
        counts[r["class"]] = counts.get(r["class"], 0) + 1
    data = {"schema": "kerotakis/iodine-observables-coverage-v1", "solvent": "hexane",
            "counts": counts, "cases": CASES, "species": rows}
    md = ["# Iodine-observable coverage (2026-11-11)", "",
          "Generated by `tools/iodine_observables_coverage.py --check`.", "",
          "## Lane cases", "", "| id | observable | status | mechanism |", "|---|---|---|---|"]
    md += [f"| {c['id']} | {c['observable']} | {c['status']} | {c['mechanism']} |" for c in CASES]
    md += ["", "## Hexane/water extract classes", "",
           "Ions are kept in the water as a stated model boundary (electroneutrality: one ion cannot",
           "enter the organic layer without a counter-ion, and no ion-pair partition is modelled); it is",
           "not a measured zero coefficient. Partition rows and their sources are in",
           "`docs/separation-coverage-20261109.md` (I2: K = 85; aqueous solubility Hartley & Campbell,",
           "J. Chem. Soc. Trans. 93 (1908) 741-745, doi:10.1039/CT9089300741).", "",
           f"Counts: {', '.join(f'{k} {v}' for k, v in sorted(counts.items()))}.", "",
           "| class | species | basis |", "|---|---|---|"]
    md += [f"| {r['class']} | {r['species']} | {r['basis'] or '—'} |" for r in rows]
    return "\n".join(md) + "\n", json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    md, js = build()
    if a.check:
        stale = [p.name for p, t in ((OUT_MD, md), (OUT_JSON, js))
                 if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            print("stale: " + ", ".join(stale) + "; rerun tools/iodine_observables_coverage.py", file=sys.stderr)
            return 1
        return 0
    OUT_MD.write_text(md, encoding="utf-8")
    OUT_JSON.write_text(js, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
