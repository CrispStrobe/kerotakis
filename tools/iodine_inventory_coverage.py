#!/usr/bin/env python3
"""Iodine-inventory coverage of `inspect` (AN-004, 2026-11-11).

Classifies every registry species that carries iodine into the pool
`iodine_chemistry::iodine_inventory` puts it in when present in a vessel:

  split-oxidised   aqueous I2: free I2 / I3- / starch-bound complex
  split-iodide     aqueous I- and every Na/K iodide salt (registry_forms("I-")):
                   free I- / I3- / starch-bound complex
  other-pool       every other iodine-bearing portion (and any phase of the two
                   above outside liquid water), reported by formula iodine atoms

Every class closes against the ledger's iodine atoms. Writes
docs/iodine-inventory-coverage-20261111.md/.json; `--check` fails when stale.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "crates/kerotakis-core/src/iodine_chemistry.rs"
STARCH = ROOT / "crates/kerotakis-core/src/starch_iodine.rs"
REG = ROOT / "data/registry/registry-source-v1.json"
MD = ROOT / "docs/iodine-inventory-coverage-20261111.md"
JS = ROOT / "docs/iodine-inventory-coverage-20261111.json"

SOURCES = [
    "Triiodide K = 698 L/mol at 25 C: Palmer, Ramette & Mesmer, J. Solution Chem. 13 (1984) 673, "
    "doi:10.1007/BF00650374 (spectrophotometric range 698-770: Awtrey & Connick, J. Am. Chem. Soc. 73 "
    "(1951) 1842, doi:10.1021/ja01148a097).",
    "Starch-iodine binding stoichiometry NOT settled (hence the editorial site fraction and the typed "
    "limitation): Pesek et al., Molecules 27 (2022) 8974, doi:10.3390/molecules27248974; Pesek & "
    "Silaghi-Dumitrescu, Molecules 29 (2024) 641, doi:10.3390/molecules29030641.",
]


def const(text: str, name: str) -> float:
    m = re.search(rf"const {name}: f64 = ([0-9_.eE+-]+);", text)
    return float(m.group(1).replace("_", ""))


def build():
    src = SRC.read_text(encoding="utf-8")
    starch = STARCH.read_text(encoding="utf-8")
    key = re.search(r'pub const STARCH_BINDING_LIMITATION: &str =\s*"([^"]+)"', src).group(1)
    reg = json.loads(REG.read_text(encoding="utf-8"))
    rows = []
    for c in reg["compositions"]:
        el = {e["element"]: e["count"]["value"] for e in c["elements"]}
        n = el.get("I", 0.0)
        if not n:
            continue
        charge = c["net_charge"]["value"]
        rest = {k: v for k, v in el.items() if k != "I"}
        sid = c["species_id"]
        if sid == "I2":
            cls = "split-oxidised (aqueous)"
        elif sid == "I-" or (charge == 0 and n == 1 and len(rest) == 1
                             and set(rest) <= {"Na", "K"} and list(rest.values()) == [1.0]):
            cls = "split-iodide (aqueous)"
        else:
            cls = "other-pool"
        rows.append({"species": sid, "formula": c["formula"], "iodine_atoms": n, "class": cls})
    rows.sort(key=lambda r: (r["class"], r["species"]))
    return {
        "generated_by": "tools/iodine_inventory_coverage.py",
        "constants": {
            "triiodide_k": const(src, "TRIIODIDE_K"),
            "starch_site_fraction": const(starch, "STARCH_SITE_FRACTION"),
        },
        "starch_binding_limitation": key,
        "species": rows,
        "sources": SOURCES,
    }


def markdown(doc) -> str:
    c = doc["constants"]
    md = ["# Iodine-inventory coverage of `inspect` (2026-11-11)", "",
          "Generated by `tools/iodine_inventory_coverage.py --check`. AN-004: the inspect",
          "`iodine_speciation` block omitted the starch-bound triiodide and dropped a vessel whose",
          "iodine was all starch-bound. It is now `iodine_chemistry::iodine_inventory` per vessel:",
          "free I2, I3-, free I-, the starch-bound complex (I3- equivalents) and every other",
          "iodine-bearing portion, closed against the ledger's iodine atoms",
          "(`closure_residual_mol`). Once any vessel holds iodine, every vessel is listed.", "",
          "| constant | value | status |", "|---|---|---|",
          f"| triiodide K (L/mol, 25 C) | {c['triiodide_k']:g} | sourced (Palmer et al. 1984) |",
          f"| starch sites per anhydroglucose | {c['starch_site_fraction']:g} | EDITORIAL bound, not sourced |",
          "",
          "A non-zero starch-bound pool always carries the typed limitation",
          f"`{doc['starch_binding_limitation']}` (EN/DE/FR): the binding stoichiometry is not settled,",
          "so the bound amount is an upper-bounded editorial estimate, not a measured quantity.", "",
          "| species | formula | I atoms | pool class |", "|---|---|---|---|"]
    md += [f"| {r['species']} | {r['formula']} | {r['iodine_atoms']:g} | {r['class']} |" for r in doc["species"]]
    md += ["", "Species whose formula does not parse but may name iodine are listed as",
           "`unresolved_species`, never counted as zero.", "", "## Sources", ""]
    md += [f"- {s}" for s in doc["sources"]]
    return "\n".join(md) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    doc = build()
    js = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
    md = markdown(doc)
    if a.check:
        stale = [p for p, t in ((JS, js), (MD, md)) if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            print("stale: " + ", ".join(str(p.relative_to(ROOT)) for p in stale) +
                  " (run python3 tools/iodine_inventory_coverage.py)", file=sys.stderr)
            return 1
        print(f"iodine inventory coverage current: {len(doc['species'])} iodine species")
        return 0
    JS.write_text(js, encoding="utf-8")
    MD.write_text(md, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
