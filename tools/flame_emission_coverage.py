#!/usr/bin/env python3
"""Flame-emission coverage of the flame test (2026-11-10).

Reads the cation table `EMISSIONS` from crates/kerotakis-core/src/flame.rs and
classifies every registry species that carries a metal (same nonmetal list as
`flame::NONMETALS`):

  emits        every metal in it has a row (or the species has a curated colour)
  refused      a metal without a row: `not-modeled.flame-emission-no-data`

Writes docs/flame-emission-coverage-20261110.md; `--check` fails when stale.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "crates/kerotakis-core/src/flame.rs"
OUT = ROOT / "docs/flame-emission-coverage-20261110.md"


def table():
    src = SRC.read_text(encoding="utf-8").split("#[cfg(test)]")[0]
    body = src[src.index("pub const EMISSIONS"):src.index("];", src.index("pub const EMISSIONS"))]
    rows = []
    for m in re.finditer(r"CationEmission \{(.*?)\n    \}", body, re.S):
        b = m.group(1)
        band = re.search(r'band_emitter: Some\("([^"]+)"\)', b)
        rows.append(dict(
            element=re.search(r'element: "([^"]+)"', b).group(1),
            colour=re.search(r'colour: "([^"]+)"', b).group(1),
            lines=[float(x) for x in re.findall(r"[\d.]+", re.search(r"lines_nm: &\[([^\]]*)\]", b).group(1))],
            band=band.group(1) if band else None,
            masked="masked_by_sodium: true" in b,
        ))
    nonmetals = re.findall(r'"(\w+)"', src[src.index("const NONMETALS"):src.index("];", src.index("const NONMETALS"))])
    return rows, set(nonmetals)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rows, nonmetals = table()
    have = {r["element"] for r in rows}
    reg = json.loads((ROOT / "data/registry/registry-source-v1.json").read_text(encoding="utf-8"))
    flame = {o["species_id"]: o.get("flame_colour") for o in reg["optical"]}
    species = []
    for c in reg["compositions"]:
        metals = sorted({e["element"] for e in c["elements"]} - nonmetals)
        if not metals:
            continue
        missing = [m for m in metals if m not in have]
        curated = flame.get(c["species_id"]) if len(metals) == 1 else None
        cls = "emits" if not missing or curated else "refused"
        species.append((cls, c["species_id"], "+".join(metals), curated or "—"))
    species.sort()
    counts = {}
    for s in species:
        counts[s[0]] = counts.get(s[0], 0) + 1
    md = ["# Flame-emission coverage of the flame test (2026-11-10)", "",
          "Generated by `tools/flame_emission_coverage.py --check` from `flame::EMISSIONS` and the",
          "registry source document. A salt held in a flame is a flame test, never a combustion:",
          "each cation with a row is reported; a cation without one is refused with",
          "`not-modeled.flame-emission-no-data` (EN/DE/FR). Sodium's yellow masks the cations marked",
          "below, and the flame-test event says so (`masked_by`).", "",
          "Sources: atomic lines from the NIST Atomic Spectra Database (Kramida, Ralchenko, Reader and",
          "NIST ASD Team, v5.11, air wavelengths). Molecular band emitters (the visible colour of Ca, Sr,",
          "Ba, Cu flames) from Pearse and Gaydon, *The Identification of Molecular Spectra*, 4th ed., 1976.", "",
          "| cation | colour | atomic lines (nm) | band emitter | masked by Na |", "|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['element']} | {r['colour']} | {', '.join(f'{x:.3f}' for x in r['lines'])} | "
                  f"{r['band'] or '—'} | {'yes' if r['masked'] else 'no'} |")
    md += ["", f"Registry species carrying a metal: {', '.join(f'{k} {v}' for k, v in sorted(counts.items()))}.", "",
           "| class | species | metals | curated colour |", "|---|---|---|---|"]
    md += [f"| {c} | {s} | {m} | {f} |" for c, s, m, f in species]
    text = "\n".join(md) + "\n"
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("stale:", OUT, file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(json.dumps(counts))
    return 0


if __name__ == "__main__":
    sys.exit(main())
