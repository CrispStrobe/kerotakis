#!/usr/bin/env python3
"""Coverage of held two-state fast-redox respeciation (EC-008 / RX-004 family).

When the ledger holds a FAST_REDOX element (aqueous.rs) in two or more
oxidation states with no second fast element to couple to -- iron(II) and
iron(III) after the curated Fe3+/I- step -- the aqueous solve is posed from
that split (valence-tagged totals, no O2(g) pe) when the routed database
defines every held state as a master species and every other redox element
present is a RESPECIATION_SAFE_PARTNER. Otherwise the view is refused with
`not-modeled.redox-split-not-respeciated`.

This table lists, per routed database and fast element, the tagged states the
database can pose, read from the vendored .dat SOLUTION_MASTER_SPECIES. The
runtime test `respeciation_coverage_is_current` (crates/kerotakis-phreeqc/
tests/redox_respeciation.rs) holds the JSON to `posable_fast_redox_states`.
minteq.v4 rows are read from the upstream file; the engine's reviewed
additions to it define no new fast-redox masters.

Usage: python3 tools/redox_respeciation_coverage.py [--check] [--db-dir DIR]
(--db-dir: a checkout of vendor/iphreeqc/database at the pinned submodule commit)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AQ = ROOT / "crates/kerotakis-phreeqc/src/aqueous.rs"
DB_DIR = ROOT / "vendor/iphreeqc/database"
DBS = [("wateq4f", "wateq4f.dat"), ("minteq.v4", "minteq.v4.dat")]
JSON_OUT = ROOT / "docs/redox-respeciation-coverage-20261111.json"
MD_OUT = ROOT / "docs/redox-respeciation-coverage-20261111.md"


def const_list(src, name):
    m = re.search(r"const %s: &\[&str\] = &\[([^\]]*)\];" % name, src)
    if not m:
        sys.exit(f"cannot find {name} in {AQ}")
    return re.findall(r'"([^"]+)"', m.group(1))


def master_states(path):
    states = {}
    text = path.read_bytes().decode("latin-1")
    block = False
    for line in text.splitlines():
        s = line.split("#", 1)[0].strip()
        if not s:
            continue
        if re.match(r"^[A-Z_]+$", s.split()[0]) and s.split()[0].isupper() and len(s.split()) == 1:
            block = s == "SOLUTION_MASTER_SPECIES"
            continue
        if not block:
            continue
        m = re.match(r"^([A-Z][a-z]?)\(([+-]?\d+)\)\s", s)
        if m:
            states.setdefault(m.group(1), set()).add(int(m.group(2)))
    return states


def build(db_dir):
    src = AQ.read_text(encoding="utf-8")
    fast = const_list(src, "FAST_REDOX")
    safe = const_list(src, "RESPECIATION_SAFE_PARTNERS")
    rows = []
    for tag, fname in DBS:
        path = db_dir / fname
        if not path.exists():
            sys.exit(f"missing {path}: run `git submodule update --init vendor/iphreeqc`")
        states = master_states(path)
        for base in fast:
            st = sorted(states.get(base, ()))
            rows.append({
                "database": tag,
                "element": base,
                "posable_states": st,
                "held_split": "respeciated_from_ledger" if len(st) >= 2 else "no_redox_states_on_this_database",
            })
    return {
        "lane": "EC-008/RX-004 held fast-redox split respeciation",
        "date": "2026-11-11",
        "refusal_key": "not-modeled.redox-split-not-respeciated",
        "fast_redox": fast,
        "safe_partners": safe,
        "rows": rows,
        "sources": [
            "Singer P.C., Stumm W., Science 167 (1970) 1121, doi:10.1126/science.167.3921.1121 (Fe(II) oxygenation slow below pH ~4)",
            "Stumm W., Morgan J.J., Aquatic Chemistry, 3rd ed., Wiley 1996, ISBN 0-471-51185-4, ch. 8 (redox ladder ordering; qualitative only)",
        ],
    }


def markdown(doc):
    out = [
        "# Held fast-redox split respeciation coverage (2026-11-11)",
        "",
        "Generated by `python3 tools/redox_respeciation_coverage.py`; held by `--check` and by",
        "`respeciation_coverage_is_current` in `crates/kerotakis-phreeqc/tests/redox_respeciation.rs`.",
        "",
        "## Defect (EC-008, RX-004)",
        "",
        "After the curated `2 Fe3+ + 2 I- -> 2 Fe2+ + I2` step the ledger held iron in two",
        "states, but the aqueous solve still fixed pe from atmospheric O2(g). PHREEQC's reaction",
        "step re-oxidised ferrous iron with dissolved oxygen the bench never booked; the",
        "inventory kept the ledger split, the reported speciation/redox block/pe did not",
        "(RX-004: 47 % ferric in the view vs 20 % in the ledger; EC-008: 28 % vs 1.4 %), and the",
        "UV-vis refusal listed ferric species from that view.",
        "",
        "## Mechanism (generic over FAST_REDOX)",
        "",
        "For any fast-redox element held in two or more states with no fast partner, on the",
        "direct and MIX paths: totals are written valence-tagged (the untagged booking key",
        "`Fe` becomes `Fe(2)`), and the O2(g) pe pin is dropped, so the reaction step's",
        "electron balance is the held couple's own. Without the O2 poise the input carries no",
        "pe authority, so the potential is withheld rather than published (`PeAuthority`). Admission requires every held state to be",
        "a master species of the routed database and every other redox element present to be",
        f"one of {', '.join(doc['safe_partners'])} (slow couples not reduced at those potentials).",
        f"Anything else emits `{doc['refusal_key']}` (EN/DE/FR) instead of a silent view.",
        "",
        "The I2/I3- pool itself is not in the aqueous databases (iodine is I- only); it stays",
        "owned by the curated iodine ledger and `inspect` iodine speciation.",
        "",
        "| database | element | posable states | held split |",
        "|---|---|---|---|",
    ]
    for r in doc["rows"]:
        st = ", ".join(str(s) for s in r["posable_states"]) or "none"
        out.append(f"| {r['database']} | {r['element']} | {st} | {r['held_split']} |")
    out += ["", "## Sources", ""] + [f"- {s}" for s in doc["sources"]] + [""]
    return "\n".join(out)


def main():
    db_dir = DB_DIR
    if "--db-dir" in sys.argv:
        db_dir = Path(sys.argv[sys.argv.index("--db-dir") + 1])
    doc = build(db_dir)
    js = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
    md = markdown(doc)
    if "--check" in sys.argv:
        bad = [p for p, c in ((JSON_OUT, js), (MD_OUT, md)) if not p.exists() or p.read_text(encoding="utf-8") != c]
        if bad:
            sys.exit("stale: " + ", ".join(str(p) for p in bad) + " (run tools/redox_respeciation_coverage.py)")
        print("redox respeciation coverage current")
        return
    JSON_OUT.write_text(js, encoding="utf-8")
    MD_OUT.write_text(md, encoding="utf-8")
    print(f"wrote {JSON_OUT} and {MD_OUT}")


if __name__ == "__main__":
    main()
